/**
 * Получить статью по ID
 */
export function getArticleById(id: string): TrafficArticle | undefined {
  return TRAFFIC_ARTICLES.find(article => article.id === id);
}

/**
 * Получить статьи по категории
 */
export function getArticlesByCategory(category: 'cat' | 'dog'): TrafficArticle[] {
  return TRAFFIC_ARTICLES.filter(article => article.category === category);
}

/**
 * Получить все статьи
 */
export function getAllArticles(): TrafficArticle[] {
  return TRAFFIC_ARTICLES;
}
